    private fun percentileValue(table: DoubleArray, percent: Double): Double {
        val clamped = percent.coerceIn(0.0, 100.0)
        val lowerIndex = clamped.toInt()
        val upperIndex = (lowerIndex + 1).coerceAtMost(table.size - 1)
        val remainder = clamped - lowerIndex
        return table[lowerIndex] + (table[upperIndex] - table[lowerIndex]) * remainder
    }

    private fun percentAtValue(table: DoubleArray, value: Double): Double {
        if (value <= table[0]) return 0.0
        if (value >= table[table.size - 1]) return (table.size - 1).toDouble()

        var low = 0
        var high = table.size - 1
        while (low < high) {
            val mid = (low + high) / 2
            if (table[mid] < value) low = mid + 1 else high = mid
        }
        val lowerValue = table[low - 1]
        val upperValue = table[low]
        val fraction = if (upperValue > lowerValue) (value - lowerValue) / (upperValue - lowerValue) else 0.0
        return (low - 1).toDouble() + fraction
    }

    fun faultThresholdForPercent(percent: Double): Double =
        percentileValue(FAULT_DISTANCE_PERCENTILES, percent)

    fun percentForFaultThreshold(threshold: Double): Double =
        percentAtValue(FAULT_DISTANCE_PERCENTILES, threshold)

    fun trenchThresholdForPercent(percent: Double): Double =
        (1.0 - percentileValue(TRENCH_DISTANCE_PERCENTILES, percent)).coerceIn(0.0, 1.0)

    fun percentForTrenchThreshold(threshold: Double): Double =
        percentAtValue(TRENCH_DISTANCE_PERCENTILES, (1.0 - threshold).coerceIn(0.0, 1.0))

    fun terraceThresholdForPercent(percent: Double): Double =
        percentileValue(TERRACE_MASK_PERCENTILES, 100.0 - percent)

    fun percentForTerraceThreshold(threshold: Double): Double =
        100.0 - percentAtValue(TERRACE_MASK_PERCENTILES, threshold)
